"""
Heuristics Registry — persisted JSON rules applied inside the alpha engine.

Rules are generated by the post-mortem engine and applied in alpha.evaluate()
before returning a signal. Rules modify the signal in one of four ways:
  skip_trade          — block signal entirely (direction → NO_TRADE)
  scale_position      — multiply Kelly fraction by `factor`
  shift_threshold     — override XGB_YES/NO_THRESHOLD for this bar
  reduce_edge_requirement — lower min_net_edge in high-confidence regimes

Each rule has a confidence score (0-1) that decays over time:
  confidence = 0.7 × recent_win_rate(last 30 matching trades)
             + 0.3 × historical_win_rate(all time)

Rules below 0.55 confidence are auto-disabled.
Rules above 0.65 with ≥50 trade basis are promoted to "stable".
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from loguru import logger


HEURISTICS_PATH = Path("data/heuristics.json")
MIN_CONFIDENCE  = 0.55
PROMOTE_CONFIDENCE = 0.65
PROMOTE_MIN_TRADES = 50


def _default_rules() -> List[Dict]:
    return []


class HeuristicsEngine:
    """
    Loads rules from heuristics.json and applies them to each TradeSignal.

    Usage (inside alpha.evaluate()):
        signal = heuristics_engine.apply(features, signal, market)
    """

    def __init__(self, path: Path = HEURISTICS_PATH):
        self._path = path
        self._rules: List[Dict] = []
        self.load()

    def load(self) -> None:
        """Reload rules from disk."""
        if self._path.exists():
            try:
                data = json.loads(self._path.read_text())
                self._rules = data.get("rules", [])
                enabled = sum(1 for r in self._rules if r.get("enabled", False))
                logger.debug(f"HeuristicsEngine: loaded {len(self._rules)} rules ({enabled} enabled).")
            except Exception as exc:
                logger.warning(f"HeuristicsEngine: failed to load rules: {exc}")
                self._rules = []
        else:
            self._rules = []

    def save(self) -> None:
        """Persist current rules to disk."""
        self._path.parent.mkdir(parents=True, exist_ok=True)
        data = {"rules": self._rules, "updated_ts": time.time()}
        self._path.write_text(json.dumps(data, indent=2))

    @property
    def _enabled_rules(self) -> List[Dict]:
        return [r for r in self._rules if r.get("enabled", False)]

    def apply(self, features: Dict[str, float], signal, market) -> Any:
        """
        Apply all enabled heuristic rules to signal.
        Returns potentially modified signal.
        """
        from src.engine.alpha import Direction, TradeSignal
        import dataclasses

        for rule in self._enabled_rules:
            try:
                if self._matches(rule["condition"], features, signal, market):
                    signal = self._apply_action(rule["action"], signal)
                    if signal.direction == Direction.NO_TRADE:
                        break  # no need to continue if already blocked
            except Exception as exc:
                logger.debug(f"Heuristic rule {rule.get('rule_id')} error: {exc}")

        return signal

    def add_rule(self, rule: Dict) -> None:
        """Add a new rule (from post-mortem engine)."""
        # Avoid duplicates by rule_id
        existing_ids = {r.get("rule_id") for r in self._rules}
        if rule.get("rule_id") in existing_ids:
            logger.debug(f"Rule {rule['rule_id']} already exists; skipping.")
            return
        self._rules.append(rule)
        self.save()
        logger.info(f"HeuristicsEngine: added rule {rule.get('rule_id')} — {rule.get('name')}")

    def update_confidence(self, rule_id: str, new_confidence: float, n_trades: int) -> None:
        """Update confidence for a rule; auto-disable if below threshold."""
        for rule in self._rules:
            if rule.get("rule_id") == rule_id:
                rule["confidence"] = new_confidence
                rule["n_trades_basis"] = n_trades
                rule["last_validated_ts"] = time.time()

                if new_confidence < MIN_CONFIDENCE:
                    rule["enabled"] = False
                    logger.info(
                        f"Rule {rule_id} auto-disabled (confidence={new_confidence:.2f} < {MIN_CONFIDENCE})"
                    )
                elif new_confidence >= PROMOTE_CONFIDENCE and n_trades >= PROMOTE_MIN_TRADES:
                    rule["status"] = "stable"
                    logger.info(
                        f"Rule {rule_id} promoted to STABLE (confidence={new_confidence:.2f})"
                    )
                break
        self.save()

    def get_rules_summary(self) -> List[Dict]:
        """Return lightweight summary of all rules."""
        return [
            {
                "rule_id": r.get("rule_id"),
                "name": r.get("name"),
                "enabled": r.get("enabled"),
                "confidence": r.get("confidence"),
                "n_trades_basis": r.get("n_trades_basis"),
            }
            for r in self._rules
        ]

    # ── Rule matching ────────────────────────────────────────────────────

    def _matches(self, condition: Dict, features: Dict, signal, market) -> bool:
        """
        Evaluate a condition dict against current bar state.

        Condition fields:
          feature : feature name or "regime" or "direction"
          op      : ">" | "<" | "==" | "abs<" | "abs>"
          value   : threshold
          also    : optional nested condition (AND logic)
        """
        primary = self._eval_condition(condition, features, signal, market)
        if not primary:
            return False
        if "also" in condition:
            return self._eval_condition(condition["also"], features, signal, market)
        return True

    def _eval_condition(self, cond: Dict, features: Dict, signal, market) -> bool:
        fname = cond.get("feature", "")
        op    = cond.get("op", ">")
        value = cond.get("value")

        # Special fields
        if fname == "regime":
            actual = getattr(signal, "regime", features.get("regime", "trending"))
        elif fname == "direction":
            actual = signal.direction.value
        else:
            actual = features.get(fname, 0.0)

        if actual is None:
            actual = 0.0

        if op == ">":
            return float(actual) > float(value)
        if op == "<":
            return float(actual) < float(value)
        if op == "==":
            return str(actual) == str(value)
        if op == "abs<":
            return abs(float(actual)) < float(value)
        if op == "abs>":
            return abs(float(actual)) > float(value)
        return False

    # ── Action application ───────────────────────────────────────────────

    def _apply_action(self, action: Dict, signal):
        import dataclasses
        from src.engine.alpha import Direction

        action_type = action.get("type")

        if action_type == "skip_trade":
            signal = dataclasses.replace(signal, direction=Direction.NO_TRADE)
            logger.debug("Heuristic: skip_trade applied.")

        elif action_type == "scale_position":
            # Tag the signal so the controller can use it for sizing
            # We store the scale factor as a custom attribute
            factor = float(action.get("factor", 1.0))
            try:
                signal = dataclasses.replace(signal, net_edge=signal.net_edge * factor)
            except Exception:
                pass
            logger.debug(f"Heuristic: scale_position factor={factor}")

        elif action_type == "reduce_edge_requirement":
            # Artificially boost net_edge so the trade passes the min_net_edge filter
            boost = float(action.get("boost", 0.01))
            try:
                signal = dataclasses.replace(signal, net_edge=signal.net_edge + boost)
            except Exception:
                pass
            logger.debug(f"Heuristic: reduce_edge_requirement boost={boost}")

        return signal
